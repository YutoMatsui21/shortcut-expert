// Run only a read-only aggregate fixture; never launch the product's real observation entry.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { build } from 'esbuild';
import { packageManifest } from './ui-acceptance-runtime.mjs';
const workspace = resolve('.');
const packageRoot = resolve('release/issue-47-top-threshold/win-unpacked');
const expected = JSON.parse(readFileSync('validation/evidence/issue-47/top-threshold-build.json','utf8'));
const hash = value => createHash('sha256').update(value).digest('hex');
const before = hash(JSON.stringify(packageManifest(packageRoot)));
assert.equal(before, expected.manifestSha256, 'Frozen package mismatch');
const installedVersion = JSON.parse(readFileSync('node_modules/electron/package.json','utf8')).version;
assert.equal(installedVersion, JSON.parse(readFileSync('package.json','utf8')).devDependencies.electron);
mkdirSync('.tools/validation',{recursive:true});
const root = mkdtempSync(resolve('.tools/validation/issue47-renderer-'));
const harness = resolve('validation/issue-47/records-renderer-replay.ts');
const output = join(root,'replay.cjs');
await build({absWorkingDir:workspace,entryPoints:[harness],bundle:true,platform:'node',format:'cjs',external:['electron'],tsconfig:'tsconfig.json',outfile:output,logLevel:'warning'});
const env = {...process.env,COACH_E47_REPLAY_ROOT:root,COACH_E47_PACKAGE_ROOT:packageRoot};
delete env.ELECTRON_RUN_AS_NODE;delete env.ELECTRON_RENDERER_URL;
const child = spawn(resolve('node_modules/electron/dist/electron.exe'),[output],{env,windowsHide:true,stdio:['ignore','pipe','pipe']});
let succeeded = false;
child.stdout.on('data',chunk => {if(chunk.toString().split(/\r?\n/).includes('RECORDS_REPLAY_OK'))succeeded=true;});
// Do not persist arbitrary OS/application messages or image data.
child.stderr.on('data',()=>{});
const timer = setTimeout(()=>child.kill(),45_000);
const exited = await new Promise((yes,no)=>{child.once('error',no);child.once('close',(code,signal)=>yes({code,signal}));});
clearTimeout(timer);
assert.equal(exited.code,0,'Fixture process failed');assert.equal(exited.signal,null);assert.equal(succeeded,true);
const report = JSON.parse(readFileSync(join(root,'report.json'),'utf8'));
assert.equal(report.fixtureOnly,true);assert.equal(report.nativeHelperStarted,false);assert.equal(report.originalDbWritten,false);
assert.equal(report.runtimeElectronVersion,installedVersion);
assert.equal(report.realInputObserved,false);assert.equal(report.screenshotsSaved,false);assert.equal(report.passed,true);
assert.equal(hash(JSON.stringify(packageManifest(packageRoot))),before,'Frozen package changed');
report.packageManifestSha256=before;report.harnessSha256=hash(readFileSync(harness));report.electronVersion=installedVersion;report.exit=exited;
writeFileSync('validation/evidence/issue-47/session26-renderer-replay.json',JSON.stringify(report,null,2));
console.log('RECORDS_REPLAY_OK: unchanged package; 8 learning rows and 8 record rows; no observation/images/DB mutation');
